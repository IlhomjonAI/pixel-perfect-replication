CREATE FUNCTION archive_school_record() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE record jsonb := to_jsonb(OLD);
BEGIN
 INSERT INTO recycle_bin(resource,record_key,label,payload)
 VALUES(TG_ARGV[0],record->>TG_ARGV[1],record->>TG_ARGV[2],record::text);
 RETURN OLD;
END;
$$;
CREATE TRIGGER archive_posts BEFORE DELETE ON posts FOR EACH ROW EXECUTE FUNCTION archive_school_record('posts','slug','title');
CREATE TRIGGER archive_achievements BEFORE DELETE ON achievements FOR EACH ROW EXECUTE FUNCTION archive_school_record('achievements','id','title');
CREATE TRIGGER archive_teachers BEFORE DELETE ON teachers FOR EACH ROW EXECUTE FUNCTION archive_school_record('teachers','slug','name');
CREATE TRIGGER archive_school_life BEFORE DELETE ON school_life FOR EACH ROW EXECUTE FUNCTION archive_school_record('school-life','id','title');
CREATE TRIGGER archive_contact_messages BEFORE DELETE ON contact_messages FOR EACH ROW EXECUTE FUNCTION archive_school_record('messages','id','name');
CREATE FUNCTION restore_school_record() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE target text; record jsonb;
BEGIN
 target := CASE OLD.resource WHEN 'posts' THEN 'posts' WHEN 'achievements' THEN 'achievements'
  WHEN 'teachers' THEN 'teachers' WHEN 'school-life' THEN 'school_life' WHEN 'messages' THEN 'contact_messages' END;
 IF target IS NULL THEN RAISE EXCEPTION 'Unknown archive resource'; END IF;
 record := OLD.payload::jsonb;
 record := jsonb_set(record,'{version}',to_jsonb((record->>'version')::integer+1));
 EXECUTE format('INSERT INTO school_app.%I SELECT (jsonb_populate_record(NULL::school_app.%I,$1)).*',target,target) USING record;
 IF target='contact_messages' THEN
  UPDATE telegram_outbox SET sent_at=CURRENT_TIMESTAMP::text WHERE contact_id=(record->>'id')::bigint;
 END IF;
 DELETE FROM recycle_bin WHERE id=OLD.id;
 RETURN OLD;
END;
$$;
CREATE TRIGGER restore_school_record INSTEAD OF DELETE ON restore_bin FOR EACH ROW EXECUTE FUNCTION restore_school_record();
